import { IsBoolean, IsInt, IsOptional, IsString, Matches, Min } from 'class-validator';
import { KEY_PATTERN } from '@ims/shared';

export class CreateInventoryTypeDto {
  @Matches(KEY_PATTERN)
  code!: string;

  @IsString()
  name!: string;

  @IsOptional()
  @IsString()
  description?: string;

  @IsOptional()
  @IsInt()
  @Min(0)
  sortOrder?: number;
}

export class UpdateInventoryTypeDto {
  @IsOptional()
  @IsString()
  name?: string;

  @IsOptional()
  @IsString()
  description?: string;

  @IsOptional()
  @IsInt()
  @Min(0)
  sortOrder?: number;

  @IsOptional()
  @IsBoolean()
  isActive?: boolean;
}
